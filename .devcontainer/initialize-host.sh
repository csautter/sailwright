#!/usr/bin/env bash
# Runs on the host before the devcontainer starts (initializeCommand).
#
# Writes .devcontainer/.generated/compose.local.yaml with the bind mounts for
# this machine. Optional mounts (agent configs, sibling repos) are only added
# when their source exists, so a missing path never stops the container from
# starting. Extra personal mounts go in .devcontainer/mounts.local.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

# On Windows, `bash` may resolve to WSL's bash.exe instead of Git Bash. If the
# checkout lives on a Windows drive, VS Code and Docker Desktop run on Windows:
# use the Windows profile as home and hand Docker C:/... paths. A checkout
# inside the WSL filesystem (VS Code WSL remote) keeps the Linux paths.
WSL_WINDOWS=false
if [ -n "${WSL_DISTRO_NAME:-}" ] && command -v wslpath >/dev/null 2>&1; then
  case "$(wslpath -m "$REPO_ROOT" 2>/dev/null)" in
    [A-Za-z]:/*) WSL_WINDOWS=true ;;
  esac
fi

if $WSL_WINDOWS; then
  WIN_PROFILE="$(cd "$REPO_ROOT" && cmd.exe /d /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')" || WIN_PROFILE=""
  case "$WIN_PROFILE" in
    [A-Za-z]:\\*) USER_HOME="$(wslpath -u "$WIN_PROFILE")" ;;
    *)
      echo "Error: running under WSL but could not read the Windows USERPROFILE via cmd.exe." >&2
      exit 1
      ;;
  esac
else
  USER_HOME="${HOME:-${USERPROFILE:-}}"
fi

if [ -z "$USER_HOME" ]; then
  echo "Error: Neither HOME nor USERPROFILE is set." >&2
  exit 1
fi

REPO_NAME="$(basename "$REPO_ROOT")"
PARENT_DIR="$(dirname "$REPO_ROOT")"
GENERATED_DIR="$SCRIPT_DIR/.generated"
OUT_FILE="$GENERATED_DIR/compose.local.yaml"
LOCAL_FILE="$SCRIPT_DIR/mounts.local"

mkdir -p "$GENERATED_DIR"
TMP_FILE="$(mktemp "$GENERATED_DIR/compose.local.XXXXXX")"
trap 'rm -f "$TMP_FILE"' EXIT

MOUNTED=()
SKIPPED=()

# Compose needs host paths the Docker daemon understands (C:/... on Windows).
host_path() {
  if command -v cygpath >/dev/null 2>&1; then
    cygpath -m "$1"
  elif $WSL_WINDOWS; then
    wslpath -m "$1"
  else
    printf '%s' "$1"
  fi
}

yaml_quote() {
  local s="${1//\\/\\\\}"
  printf '"%s"' "${s//\"/\\\"}"
}

add_mount() { # source target [ro]
  {
    printf '      - type: bind\n'
    printf '        source: %s\n' "$(yaml_quote "$(host_path "$1")")"
    printf '        target: %s\n' "$(yaml_quote "$2")"
    if [ "${3:-}" = ro ]; then
      printf '        read_only: true\n'
    fi
  } >>"$TMP_FILE"
  MOUNTED+=("$1 -> $2")
}

add_if_exists() { # source target [ro]
  if [ -e "$1" ]; then
    add_mount "$@"
  else
    SKIPPED+=("$1 (not found)")
  fi
}

# Mountpoints nested inside another bind mount are created on the host side.
# A symlink there is the user's own setup: leave it alone and skip the mount.
add_nested() { # source target
  if [ -L "$1" ]; then
    SKIPPED+=("$1 (is a symlink, left untouched)")
    return
  fi
  mkdir -p "$1"
  add_mount "$1" "$2"
}

{
  printf '# Generated by .devcontainer/initialize-host.sh - do not edit.\n'
  printf 'services:\n  dev:\n    volumes:\n'
} >"$TMP_FILE"

# Always mounted; the sources are created because they are devcontainer-owned.
mkdir -p "$USER_HOME/.sailwright-gateway" "$USER_HOME/.claude-devcontainer"
add_mount "$REPO_ROOT" "/workspaces/$REPO_NAME"
add_mount "$USER_HOME/.sailwright-gateway" /run/sailwright-gateway ro
add_mount "$USER_HOME/.claude-devcontainer" /root/.claude

# Agent configuration, mounted when present on the host.
add_if_exists "$USER_HOME/.agents/skills" /root/.agents/skills
add_if_exists "$USER_HOME/.agents/skills" /root/.claude/skills
add_if_exists "$USER_HOME/.codex/skills" /root/.codex/skills
add_if_exists "$USER_HOME/.agents/agents" /root/.copilot/agents
add_if_exists "$USER_HOME/.codex/auth.json" /root/.codex-auth.json
add_if_exists "$USER_HOME/.local/share/opencode" /root/.local/share/opencode
if [ -d "$USER_HOME/.gemini" ]; then
  add_mount "$USER_HOME/.gemini" /root/.gemini
  if [ -d "$USER_HOME/.agents/skills" ]; then
    mkdir -p "$USER_HOME/.gemini/config"
    add_nested "$USER_HOME/.gemini/config/skills" /root/.gemini/config/skills
  fi
else
  SKIPPED+=("$USER_HOME/.gemini (not found)")
fi

# Sibling repositories next to this checkout.
for name in sailwright-plans sailwright-roles-private; do
  add_if_exists "$PARENT_DIR/$name" "/workspaces/$name"
done

# Personal mounts: one "source:target[:ro]" per line.
if [ -f "$LOCAL_FILE" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    case "$line" in '' | '#'*) continue ;; esac
    ro=""
    if [[ "$line" == *:ro ]]; then
      ro=ro
      line="${line%:ro}"
    fi
    source_path="${line%:*}"
    target="${line##*:}"
    if [ "$source_path" = "$line" ] || [ -z "$source_path" ] || [[ "$target" != /* ]]; then
      echo "mounts.local: ignoring malformed line (want source:target[:ro]): $line" >&2
      continue
    fi
    case "$source_path" in
      \~ | \~/*) source_path="$USER_HOME${source_path#\~}" ;;
      [A-Za-z]:*)
        if $WSL_WINDOWS; then
          source_path="$(wslpath -u "$source_path")"
        fi
        ;;
      /*) ;;
      *) source_path="$REPO_ROOT/$source_path" ;;
    esac
    add_if_exists "$source_path" "$target" "$ro"
  done <"$LOCAL_FILE"
fi

mv "$TMP_FILE" "$OUT_FILE"
trap - EXIT

echo "devcontainer mounts written to ${OUT_FILE#"$REPO_ROOT"/}"
for m in "${MOUNTED[@]}"; do echo "  mounted: $m"; done
for s in "${SKIPPED[@]+"${SKIPPED[@]}"}"; do echo "  skipped: $s"; done
