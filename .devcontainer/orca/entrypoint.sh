#!/usr/bin/env bash
# Entrypoint of the Orca per-workspace image (.devcontainer/orca/Dockerfile).
# Prepares sshd and the environment of SSH sessions for ORCA_SSH_USER (the
# devcontainer's remoteUser), then runs sshd in the foreground. Devcontainer
# lifecycle commands are run by the scripts/orca-vm/* host scripts, not here.
# Single-quoted snippets are written out verbatim and expand later.
# shellcheck disable=SC2016

set -euo pipefail

user="${ORCA_SSH_USER:-root}"
home="$(getent passwd "$user" | cut -d: -f6)"
[ -n "$home" ] || { echo "orca entrypoint: user ${user} does not exist in the image" >&2; exit 1; }
group="$(id -gn "$user")"

# Per-container host keys, generated once and kept for the container's lifetime.
if ! ls /etc/ssh/ssh_host_*_key >/dev/null 2>&1; then
    ssh-keygen -A >/dev/null
fi

if [ -z "${ORCA_SSH_PUBLIC_KEY:-}" ]; then
    echo "orca entrypoint: ORCA_SSH_PUBLIC_KEY is not set" >&2
    exit 1
fi
install -d -m 700 -o "$user" -g "$group" "${home}/.ssh"
printf '%s\n' "${ORCA_SSH_PUBLIC_KEY}" >"${home}/.ssh/authorized_keys"
chown "$user:$group" "${home}/.ssh/authorized_keys"
chmod 600 "${home}/.ssh/authorized_keys"

# sshd refuses key logins for locked accounts ("!" password); "*" means "no
# password" without locking the account.
if [ "$(getent shadow "$user" 2>/dev/null | cut -d: -f2 | cut -c1)" = '!' ] && command -v usermod >/dev/null 2>&1; then
    usermod -p '*' "$user"
fi

# sshd starts sessions with a clean environment, so persist the image ENV and
# the containerEnv passed via `docker run -e` for login shells, ~/.bashrc and
# PAM (/etc/environment). Secrets (devcontainer remoteEnv) are written by the
# host script to ~/.config/devcontainer/remote-env.sh (0600).
env_file=/etc/profile.d/00-container-env.sh
pam_env_file=/etc/environment
skip='|HOME|HOSTNAME|PWD|OLDPWD|SHLVL|TERM|_|USER|LOGNAME|SHELL|ORCA_SSH_PUBLIC_KEY|'
sq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
{
    echo "# Generated by orca-docker-ssh-entrypoint. Do not edit."
    while IFS='=' read -r name _; do
        case "$skip" in *"|${name}|"*) continue ;; esac
        case "$name" in *[!A-Za-z0-9_]*) continue ;; esac
        printf 'export %s=%s\n' "$name" "$(sq "${!name}")"
    done < <(env)
    echo '[ -r "$HOME/.config/devcontainer/remote-env.sh" ] && . "$HOME/.config/devcontainer/remote-env.sh"'
} >"$env_file"
chmod 644 "$env_file"
{
    while IFS='=' read -r name _; do
        case "$skip" in *"|${name}|"*) continue ;; esac
        case "$name" in *[!A-Za-z0-9_]*) continue ;; esac
        case "${!name}" in *'"'*|*$'\n'*) continue ;; esac
        printf '%s="%s"\n' "$name" "${!name}"
    done < <(env)
} >"$pam_env_file"

# Debian's ~/.bashrc returns early for non-interactive shells; load the
# environment before that guard so `ssh host cmd` sees it too.
hook="[ -r ${env_file} ] && . ${env_file}"
bashrc="${home}/.bashrc"
if ! grep -qxF "$hook" "$bashrc" 2>/dev/null; then
    { echo "$hook"; cat "$bashrc" 2>/dev/null || true; } >"${bashrc}.tmp"
    mv "${bashrc}.tmp" "$bashrc"
    chown "$user:$group" "$bashrc"
fi

exec /usr/sbin/sshd -D -e
