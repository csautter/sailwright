#!/usr/bin/env bash
# Validate in temporary module copies: no backend, local settings, or Terragrunt hooks.
set -euo pipefail
terraform_root=$(cd "$(dirname "$0")/.." && pwd)
work_dir=$(mktemp -d)
trap 'rm -rf "$work_dir"' EXIT
export TF_IN_AUTOMATION=1
terraform fmt -check -recursive "$terraform_root"
(cd "$terraform_root" && terragrunt hcl fmt --check)
tflint --init --config "$terraform_root/.tflint.hcl"
for module in "$terraform_root"/modules/*; do
    name=$(basename "$module")
    mkdir "$work_dir/$name"
    cp "$module"/*.tf "$work_dir/$name/"
    cp "$terraform_root/env/azure_dev/$name/.terraform.lock.hcl" "$work_dir/$name/"
    # The Azure provider is normally generated by Terragrunt. Validation needs
    # its features block, but neither credentials nor a subscription.
    printf 'provider "azurerm" {\n  features {}\n}\n' > "$work_dir/$name/ci-provider.tf"
    terraform -chdir="$work_dir/$name" init -backend=false -input=false -lockfile=readonly
    terraform -chdir="$work_dir/$name" validate
    tflint --chdir="$work_dir/$name" --config "$terraform_root/.tflint.hcl"
done
trivy config --exit-code 1 "$terraform_root/modules"
