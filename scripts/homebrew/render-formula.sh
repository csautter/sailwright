#!/usr/bin/env bash
# Render a Homebrew formula for a published sailwright release.
#
# Usage: render-formula.sh <sailwright|sailwright-gateway> <version> <checksums-file>
#
# The checksums file is the sailwright_<version>_checksums.txt release asset
# (sha256sum output). The formula is written to stdout.

set -euo pipefail

usage() {
  echo "Usage: $0 <sailwright|sailwright-gateway> <version> <checksums-file>" >&2
  exit 2
}

[[ $# -eq 3 ]] || usage

name="$1"
version="${2#v}"
checksums_file="$3"
repo_url="https://github.com/csautter/sailwright"

case "$name" in
  sailwright)
    class_name="Sailwright"
    desc="Cross-platform developer environment automation with Ansible and VMs"
    ;;
  sailwright-gateway)
    class_name="SailwrightGateway"
    desc="Host-side MCP gateway that lets agents drive a pinned sailwright binary"
    ;;
  *)
    usage
    ;;
esac

if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([.-][0-9A-Za-z.-]+)?$ ]]; then
  echo "Invalid version: $2" >&2
  exit 1
fi

if [[ ! -f "$checksums_file" ]]; then
  echo "Checksums file not found: $checksums_file" >&2
  exit 1
fi

# Print the SHA-256 of a release asset, matched by file name so that the
# directory prefix written by sha256sum does not matter.
asset_sha256() {
  local asset="$1" sha
  sha="$(awk -v asset="$asset" '{ file = $2; sub(/^\*/, "", file); sub(/.*\//, "", file); if (file == asset) { print $1; exit } }' "$checksums_file")"
  if [[ ! "$sha" =~ ^[0-9a-f]{64}$ ]]; then
    echo "No SHA-256 for $asset in $checksums_file" >&2
    exit 1
  fi
  echo "$sha"
}

# Print the url/sha256 stanza for one os/arch pair.
asset_block() {
  local os="$1" arch="$2" asset sha
  asset="${name}_${version}_${os}_${arch}.tar.gz"
  # `exit` here only leaves the command substitution; the caller runs under
  # set -e, so the failed assignment aborts the script.
  sha="$(asset_sha256 "$asset")" || exit 1
  printf '      url "%s/releases/download/v%s/%s"\n' "$repo_url" "$version" "$asset"
  printf '      sha256 "%s"' "$sha"
}

# Resolve every asset before printing anything so a missing checksum fails
# the script instead of producing a partial formula.
darwin_arm64="$(asset_block darwin arm64)"
darwin_amd64="$(asset_block darwin amd64)"
linux_arm64="$(asset_block linux arm64)"
linux_amd64="$(asset_block linux amd64)"

cat <<EOF
# typed: false
# frozen_string_literal: true

# This file is generated by scripts/homebrew/render-formula.sh in
# csautter/sailwright on every release. Do not edit it by hand.
class ${class_name} < Formula
  desc "${desc}"
  homepage "${repo_url}"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
${darwin_arm64}
    end
    on_intel do
${darwin_amd64}
    end
  end

  on_linux do
    on_arm do
${linux_arm64}
    end
    on_intel do
${linux_amd64}
    end
  end

  def install
    bin.install "${name}"
    generate_completions_from_executable(bin/"${name}", "completion")
  end

  test do
    assert_match "Usage:", shell_output("#{bin}/${name} --help")
  end
end
EOF
